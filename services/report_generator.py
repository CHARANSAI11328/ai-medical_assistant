from datetime import datetime
import json
from typing import Dict, Any

class ReportGenerator:
    """
    Generates structured, downloadable analysis reports in Markdown and JSON formats.
    """
    @staticmethod
    def generate_markdown_report(prediction_data: Dict[str, Any], explanation_data: Dict[str, Any]) -> str:
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        
        md = f"""# MediScope AI — Image Analysis & Educational Report
**Generated Date:** {now_str}  
**Notice:** *Research prototype analysis only. Not a medical diagnosis.*

---

## 1. Analysis Summary
- **Specialist Module:** {prediction_data.get('specialist_name', 'N/A')}
- **Target Modality:** {prediction_data.get('modality', 'N/A')}
- **Task Type:** {prediction_data.get('task_type', 'N/A')}
- **Predicted Finding:** `{prediction_data.get('predicted_label', 'Unknown')}`
- **Model Confidence:** {prediction_data.get('confidence', 0)*100:.1f}%
- **Evaluation Status:** {'Demo / Simulated Weights' if prediction_data.get('is_demo') else 'Live Model Weights'}

---

## 2. Model Confidence Distribution
"""
        probs = prediction_data.get('all_class_probabilities', {})
        for label, prob in probs.items():
            md += f"- **{label}:** {prob*100:.1f}%\n"

        md += f"""
---

## 3. Educational Explanation & Guidance
- **Plain Language Summary:** {explanation_data.get('summary', 'N/A')}
- **Clinical Meaning:** {explanation_data.get('plain_meaning', 'N/A')}
- **Uncertainty & Model Limitations:** {explanation_data.get('uncertainty_and_limitations', 'N/A')}
- **Urgency Guidance:** {explanation_data.get('urgency_guidance', 'N/A')}

### Recommended Questions for Healthcare Provider:
"""
        questions = explanation_data.get('questions_for_doctor', [])
        for q in questions:
            md += f"1. {q}\n"

        md += f"""
---

## 4. Safety & Regulatory Notice
{explanation_data.get('safety_disclaimer', 'MediScope AI provides research and educational assistance, NOT a medical diagnosis.')}

*Confidential research report generated by MediScope AI.*
"""
        return md

    @staticmethod
    def generate_json_report(prediction_data: Dict[str, Any], explanation_data: Dict[str, Any]) -> str:
        report_dict = {
            "application": "MediScope AI",
            "timestamp": datetime.now().isoformat(),
            "prediction": prediction_data,
            "explanation": explanation_data,
            "disclaimer": "AI-assisted educational information only. Not a clinical diagnosis."
        }
        return json.dumps(report_dict, indent=2)
